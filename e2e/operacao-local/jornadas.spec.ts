import { expect, test, type Page } from '@playwright/test'
import sharp from 'sharp'
import { readFile } from 'node:fs/promises'
import { unzipSync } from 'fflate'

const imagem = sharp({ create: { width: 8, height: 4, channels: 3, background: '#e8634b' } }).png().toBuffer()
const estado = (page: Page) => page.evaluate(() => JSON.parse(localStorage.getItem('seualbum:operacao-local:v1')!))

test.beforeEach(async ({ context, page }) => {
  await context.route('**/*', route => {
    const url = new URL(route.request().url())
    return url.origin === 'http://127.0.0.1:3121' || ['blob:', 'data:'].includes(url.protocol) ? route.continue() : route.abort()
  })
  await page.goto('/operacao-local')
  await expect(page.getByRole('heading', { name: 'Suas galerias', exact: true })).toBeVisible()
})

async function cliente(page: Page, codigo: string, aba: string) {
  await page.getByRole('button', { name: 'Visão do cliente', exact: true }).click()
  await page.getByLabel('Código de acesso', { exact: true }).fill(codigo)
  await page.getByRole('button', { name: 'Entrar na prévia', exact: true }).click()
  await page.getByRole('button', { name: aba, exact: true }).click()
}
async function publicar(page: Page, nome: string) {
  await page.getByLabel('Arquivos de lâminas', { exact: true }).setInputFiles({ name: nome, mimeType: 'image/png', buffer: await imagem })
  await expect(page.getByRole('img', { name: `Lâmina 1: ${nome}`, exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Publicar versão para o cliente', exact: true }).click()
  await page.getByRole('button', { name: 'Confirmar publicação', exact: true }).click()
}

