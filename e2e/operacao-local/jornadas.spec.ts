test('carrinho recusa sem entrega e compra aprovada libera só o original escolhido', async ({ page }) => {
  await page.getByRole('button', { name: 'Nova galeria', exact: true }).click()
  await page.getByLabel('Nome da galeria', { exact: true }).fill('Compra local completa')
  await page.getByLabel('Cliente', { exact: true }).fill('Cliente de teste')
  await page.getByRole('button', { name: 'Criar galeria', exact: true }).click()
  await page.getByLabel('Arquivos de fotos', { exact: true }).setInputFiles([
    { name: 'comprada.png', mimeType: 'image/png', buffer: await imagem },
    { name: 'nao-comprada.png', mimeType: 'image/png', buffer: await imagem },
  ])
  await expect(page.getByRole('button', { name: 'Favoritar nao-comprada.png', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Favoritar comprada.png', exact: true }).click()
  await page.getByRole('button', { name: 'Produtos e serviços', exact: true }).click()
  await page.getByRole('heading', { name: 'Coleção digital', exact: true }).locator('../..').getByRole('checkbox').check()
  await cliente(page, 'LOCAL2026', 'Loja e compras')
  await page.getByRole('button', { name: 'Adicionar pacote ao carrinho', exact: true }).click()
  await page.getByRole('button', { name: 'Revisar compra simulada', exact: true }).click()
  await page.getByRole('combobox', { name: /^Resultado do checkout/ }).selectOption('recusado_simulado')
  await page.getByRole('button', { name: 'Confirmar checkout simulado', exact: true }).click()
  await expect(page.getByRole('button', { name: /Baixar original adquirido/ })).toHaveCount(0)
  await page.getByRole('button', { name: 'Revisar compra simulada', exact: true }).click()
  await page.getByRole('combobox', { name: /^Resultado do checkout/ }).selectOption('pago_simulado')
  await page.getByRole('button', { name: 'Confirmar checkout simulado', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Baixar original adquirido comprada.png', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Baixar original adquirido nao-comprada.png', exact: true })).toHaveCount(0)
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: /ZIP/ }).click()
  const zip = await download
  const conteudo = unzipSync(await readFile((await zip.path())!))
  expect(Object.keys(conteudo)).toEqual(['0001_comprada.png'])
  expect(Buffer.from(conteudo['0001_comprada.png'])).toEqual(await imagem)
  const s = await estado(page)
  expect(s.loja.compras.map((c: { status: string }) => c.status)).toEqual(['pago_simulado', 'recusado_simulado'])
  await page.reload()
  await page.getByRole('button', { name: 'Compra local completa', exact: true }).click()
  await cliente(page, 'LOCAL2026', 'Loja e compras')
  await expect(page.getByRole('button', { name: 'Baixar original adquirido comprada.png', exact: true })).toBeVisible()
})

test('assinatura percorre atraso, pagamento, adicional, renovação e nova contratação', async ({ page }) => {
  await page.getByRole('button', { name: 'Operação', exact: true }).click()
  await page.getByRole('combobox', { name: /^Plano do ciclo/ }).selectOption('profissional')
  await page.getByRole('button', { name: 'Iniciar ciclo simulado', exact: true }).click()
  await page.getByRole('button', { name: 'Simular atraso', exact: true }).click()
  expect((await estado(page)).cicloAssinatura.status).toBe('inadimplente_simulada')
  await page.getByRole('button', { name: 'Simular pagamento', exact: true }).click()
  await page.getByRole('button', { name: 'Contratar adicional simulado', exact: true }).click()
  await page.getByRole('button', { name: 'Gerar próxima mensalidade simulada', exact: true }).click()
  const anterior = (await estado(page)).cicloAssinatura
  expect(anterior.faturas.map((f: { totalCentavos: number }) => f.totalCentavos)).toEqual([9900, 11800])
  await page.getByRole('button', { name: 'Cancelar ciclo simulado', exact: true }).click()
  await page.getByRole('combobox', { name: /^Plano do ciclo/ }).selectOption('essencial')
  await page.getByRole('button', { name: 'Iniciar novo ciclo simulado', exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: 'Operação', exact: true }).click()
  const s = await estado(page)
  expect(s.cicloAssinatura.plano.id).toBe('essencial')
  expect(s.ciclosAssinaturaAnteriores[0].faturas).toEqual(anterior.faturas)
  expect(s.ciclosAssinaturaAnteriores[0].status).toBe('cancelada')
  expect(s.galerias).toHaveLength(2)
  await expect(page.getByText('Contratos anteriores (1)', { exact: true })).toBeVisible()
})

