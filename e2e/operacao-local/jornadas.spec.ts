test('publicação exige rever o rascunho alterado por outra aba após abrir confirmação', async ({ page, context }) => {
  await page.getByRole('button', { name: 'Ensaio editorial', exact: true }).click()
  await page.getByRole('button', { name: 'Favoritar editorial.webp', exact: true }).click()
  await page.getByRole('button', { name: 'Entregar seleção', exact: true }).click()
  await page.getByRole('button', { name: 'Confirmar entrega', exact: true }).click()
  await page.getByRole('button', { name: 'Diagramação e prova', exact: true }).click()
  await page.getByRole('button', { name: 'Escolher diagramação própria', exact: true }).click()
  await page.getByRole('button', { name: 'Iniciar primeira versão', exact: true }).click()
  await page.getByLabel('Arquivos de lâminas', { exact: true }).setInputFiles({ name: 'antes.png', mimeType: 'image/png', buffer: await imagem })
  await page.getByRole('button', { name: 'Publicar versão para o cliente', exact: true }).click()
  const outra = await context.newPage()
  await outra.goto('/operacao-local')
  await outra.getByRole('button', { name: 'Ensaio editorial', exact: true }).click()
  await outra.getByRole('button', { name: 'Diagramação e prova', exact: true }).click()
  await outra.getByLabel('Arquivos de lâminas', { exact: true }).setInputFiles({ name: 'depois.png', mimeType: 'image/png', buffer: await imagem })
  await expect.poll(async () => (await estado(outra)).producao.projetos[0].versoes[0].laminas.length).toBe(2)
  await page.getByRole('button', { name: 'Confirmar publicação', exact: true }).click()
  await expect(page.locator('main [role="alert"]')).toContainText('produção mudou')
  expect((await estado(page)).producao.projetos[0].versoes[0].status).toBe('rascunho')
  await page.getByRole('button', { name: 'Continuar revisando', exact: true }).click()
  await page.getByRole('button', { name: 'Publicar versão para o cliente', exact: true }).click()
  await page.getByRole('button', { name: 'Confirmar publicação', exact: true }).click()
  expect((await estado(page)).producao.projetos[0].versoes[0].status).toBe('publicada')
  await outra.close()
})
