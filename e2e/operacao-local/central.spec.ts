import { expect, test } from '@playwright/test'
import sharp from 'sharp'
import { readFile } from 'node:fs/promises'
import { unzipSync } from 'fflate'

// PNG sintético válido; nenhuma mídia ou conta de cliente.
const imagem = sharp({ create: { width: 4, height: 4, channels: 3, background: '#e8634b' } }).png().toBuffer()

test.beforeEach(async ({ page, context }) => {
  await context.route('**/*', route => {
    const url = new URL(route.request().url())
    return url.origin === 'http://127.0.0.1:3121' || ['blob:', 'data:'].includes(url.protocol) ? route.continue() : route.abort()
  })
  await page.goto('/operacao-local')
  await expect(page.getByRole('heading', { name: 'Suas galerias', exact: true })).toBeVisible()
})

test('galeria, arquivo IndexedDB, favorito e snapshot sobrevivem à recarga', async ({ page }) => {
  await page.getByRole('button', { name: 'Nova galeria', exact: true }).click()
  await page.getByLabel('Nome da galeria', { exact: true }).fill('Galeria de teste local')
  await page.getByLabel('Cliente', { exact: true }).fill('Cliente sintético')
  await page.getByRole('button', { name: 'Criar galeria', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Galeria de teste local', exact: true })).toBeVisible()
  await page.getByLabel('Arquivos de fotos', { exact: true }).setInputFiles({ name: 'original-teste.png', mimeType: 'image/png', buffer: await imagem })
  const favorita = page.getByRole('button', { name: 'Favoritar original-teste.png', exact: true })
  await expect(favorita).toBeVisible()
  await favorita.click()
  await expect(favorita).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Entregar seleção', exact: true }).click()
  await page.getByRole('dialog', { name: 'Confirmar entrega da seleção' }).getByRole('button', { name: 'Confirmar entrega', exact: true }).click()
  await favorita.click()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Suas galerias', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Galeria de teste local', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Favoritar original-teste.png', exact: true })).toHaveAttribute('aria-pressed', 'false')
  const foto = page.getByRole('img', { name: 'original-teste.png', exact: true })
  await expect(foto).toBeVisible()
  await expect.poll(() => foto.evaluate((el: HTMLImageElement) => el.complete && el.naturalWidth > 0)).toBe(true)
  await page.getByRole('button', { name: 'Seleções entregues', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Revisão 1 · 1 fotos', exact: true })).toBeVisible()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Exportar CSV', exact: true }).click()
  expect((await download).suggestedFilename()).toBe('selecao-revisao-1.csv')
  const zipDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Baixar originais ZIP', exact: true }).click()
  const zip = await zipDownload
  expect(zip.suggestedFilename()).toBe('selecao-revisao-1.zip')
  const conteudo = unzipSync(await readFile((await zip.path())!))
  expect(Object.keys(conteudo)).toEqual(['0001_original-teste.png'])
  expect(Buffer.from(conteudo['0001_original-teste.png'])).toEqual(await imagem)
})

