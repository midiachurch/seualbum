import { expect, test } from '@playwright/test'
const link='a'.repeat(64)
const proxy='http://127.0.0.1:3313'
test('visitante entrega seleção real e perde acesso após revogação',async({page,context,request})=>{
  // Somente a mídia é substituída: os comandos e leituras usam Next + PostgREST + SQL reais.
  await page.route(`**/portal/${link}/foto/**`,route=>route.fulfill({contentType:'image/svg+xml',body:'<svg xmlns="http://www.w3.org/2000/svg" width="80" height="80"><rect width="80" height="80" fill="#ccc"/></svg>'}))
  await page.goto(`/portal/${link}`)
  await expect(page.getByRole('heading',{name:'Sua galeria privada'})).toBeVisible()
  await page.getByLabel('Código de acesso').fill('12345678')
  await page.getByRole('button',{name:'Entrar na galeria',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Portal browser sintético',exact:true})).toBeVisible()
  const cookies=await context.cookies(`http://127.0.0.1:3314/portal/${link}`)
  const session=cookies.find(c=>c.name==='seualbum_portal')
  expect(session?.httpOnly).toBe(true)
  expect(session?.sameSite).toBe('Lax')
  expect(session?.path).toBe(`/portal/${link}`)
  expect(cookies.some(c=>c.name.startsWith('sb-'))).toBe(false)
  await page.getByRole('button',{name:'Marcar como favorita',exact:true}).click()
  await expect(page.getByRole('status')).toContainText('1 fotos favoritas')
  await page.reload()
  await expect(page.getByRole('button',{name:'Remover dos favoritos',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Entregar seleção',exact:true}).click()
  await page.getByRole('button',{name:'Confirmar entrega',exact:true}).click()
  await expect(page.getByRole('status')).toContainText('Seleção entregue: revisão 1')
  const state=await request.post(`${proxy}/__test/state`,{headers:{'x-test-control':process.env.SEUALBUM_PORTAL_CONTROL!}})
  expect(state.ok()).toBe(true)
  expect(await state.json()).toEqual({snapshots:1,revisao:1,notificacoes:1})
  const revoke=await request.post(`${proxy}/__test/revoke`,{headers:{'x-test-control':process.env.SEUALBUM_PORTAL_CONTROL!}})
  expect(revoke.ok()).toBe(true)
  await page.reload()
  await expect(page.getByRole('heading',{name:'Sua galeria privada'})).toBeVisible()
  await expect(page.getByRole('heading',{name:'Portal browser sintético',exact:true})).toHaveCount(0)
  await page.getByLabel('Código de acesso').fill('12345678')
  await page.getByRole('button',{name:'Entrar na galeria',exact:true}).click()
  await expect(page.getByRole('main').getByRole('alert')).toContainText('revogado')
})
